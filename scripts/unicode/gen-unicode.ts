// Turn the raw UCD files in data/ucd/ into the TypeScript module that
// src/core imports.
//
//   pnpm gen:unicode
//
// Offline; reads only what `pnpm fetch:unicode` saved. The output is written the
// way Biome formats it, so formatting it afterwards changes nothing.
//
// buildModule() is the whole job and has no side effects; a test compares what
// it returns with the committed file, so a change to the raw data, the settings
// or this script that was not followed by `pnpm gen:unicode` does not go unnoticed.

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
  EXTRA_BLANK_RANGES,
  KIND_BLANK,
  KIND_INK,
  KIND_OPTIONAL,
  overrideKind,
  parseBlocks,
  parseDefaultIgnorable,
  parseUnicodeData,
} from "./parse-ucd.ts";
import {
  GENERATED_FILE,
  UCD_DATA_DIR,
  UNICODE_VERSION,
} from "./unicode-config.ts";

/** The text of the generated module for `version`, and what went into it. */
export async function buildModule(version: string): Promise<{
  text: string;
  blocks: number;
  runs: number;
}> {
  const read = (file: string) =>
    readFile(path.join(UCD_DATA_DIR, file), "utf8");
  // The two files that name their version are checked against `version`, so a
  // folder left half-updated stops here instead of making a wrong table.
  const blocks = parseBlocks(await read("Blocks.txt"), version);
  const defaultIgnorable = parseDefaultIgnorable(
    await read("DerivedCoreProperties.txt"),
    version,
  );
  // Invisible by design counts as blank whatever the general category says.
  const characters = overrideKind(
    parseUnicodeData(await read("UnicodeData.txt")),
    [...defaultIgnorable, ...EXTRA_BLANK_RANGES],
    KIND_BLANK,
  );

  const hex = (n: number) => `0x${n.toString(16)}`;
  const rows = blocks
    .map(
      (b) => `  [${hex(b.start)}, ${hex(b.end)}, ${JSON.stringify(b.name)}],`,
    )
    .join("\n");

  const runRows = characters
    .map((r) => `  [${hex(r.start)}, ${hex(r.end)}, ${r.kind}],`)
    .join("\n");

  const output = `// Generated by scripts/unicode/gen-unicode.ts from ${UCD_DATA_DIR}/. Do not edit.
// Source: the Unicode Character Database, © Unicode, Inc.
// See https://www.unicode.org/terms_of_use.html

export const UNICODE_VERSION = ${JSON.stringify(version)};

/** One block of Blocks.txt: first code point, last code point (inclusive), name. */
export type BlockRow = readonly [start: number, end: number, name: string];

/** Ascending and non-overlapping. */
export const BLOCK_ROWS: readonly BlockRow[] = [
${rows}
];

/** What a font should do with a code point (see scripts/unicode/parse-ucd.ts). */
export const KIND_INK = ${KIND_INK};
export const KIND_BLANK = ${KIND_BLANK};
export const KIND_OPTIONAL = ${KIND_OPTIONAL};

/** One run of assigned code points of one kind: first, last (inclusive), kind. */
export type AssignedRun = readonly [start: number, end: number, kind: number];

/** Ascending and non-overlapping. Code points not in any run are unassigned. */
export const ASSIGNED_RUNS: readonly AssignedRun[] = [
${runRows}
];
`;

  return { text: output, blocks: blocks.length, runs: characters.length };
}

// Run as a command (not when a test imports it).
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { text, blocks, runs } = await buildModule(UNICODE_VERSION);
  await writeFile(GENERATED_FILE, text);
  console.log(
    `${GENERATED_FILE}: ${blocks} blocks, ${runs} runs (Unicode ${UNICODE_VERSION})`,
  );
}
